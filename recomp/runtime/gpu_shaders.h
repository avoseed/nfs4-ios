/* Glide pixel pipeline as GPU shaders. The HLSL (Windows dev host) and MSL (iOS) versions
 * implement the same logic as shade_pixel() in hle_glide.c; keep the three in sync. */
#pragma once

#define GLIDE_SHADER_COMMON_DOC \
    "texture combine -> alpha/colour combine -> chroma key -> alpha test -> fog;" \
    " depth and blending are fixed-function."

static const char GPU_HLSL[] =
"cbuffer VS : register(b0) { float4 vsize; };\n"
"cbuffer PS : register(b1) {\n"
"  int4 cc; int4 ac; int4 tcm; int4 flags; int4 mode;\n"
"  float4 aref; float4 chroma; float4 fogc; float4 constc; float4 fogtab4[16];\n"
"};\n"
"Texture2D tex0 : register(t0);\n"
"SamplerState smp0 : register(s0);\n"
"struct VIn { float4 p : POSITION; float2 st : TEXCOORD0; float fog : TEXCOORD1; float4 col : COLOR0; };\n"
"struct VOut { float4 pos : SV_Position; float2 st : TEXCOORD0;\n"
"  noperspective float4 col : COLOR0; noperspective float oow : TEXCOORD1; noperspective float fog : TEXCOORD2; };\n"
"VOut vs_main(VIn i) {\n"
"  VOut o; float w = i.p.w > 1e-7 ? 1.0 / i.p.w : 1.0;\n"
"  float2 ndc = float2(i.p.x / vsize.x * 2.0 - 1.0, 1.0 - i.p.y / vsize.y * 2.0);\n"
"  o.pos = float4(ndc * w, i.p.z * w, w); o.st = i.st; o.col = i.col; o.oow = i.p.w; o.fog = i.fog; return o; }\n"
"float fogtab(int k) { return fogtab4[k >> 2][k & 3]; }\n"
"float fv(int f, float l, float la, float oa, float ta) {\n"
"  int k = f & 7; float v = k == 0 ? 0.0 : k == 1 ? l : k == 2 ? oa : k == 3 ? la : k == 4 ? ta : 1.0;\n"
"  return (f & 8) ? 1.0 - v : v; }\n"
"float comb(int fn, float f, float l, float la, float o) {\n"
"  if (fn == 0) return 0.0; if (fn == 1) return l; if (fn == 2) return la; if (fn == 3) return f * o;\n"
"  if (fn == 4) return f * o + l; if (fn == 5) return f * o + la; if (fn == 6) return f * (o - l);\n"
"  if (fn == 7) return f * (o - l) + l; if (fn == 8) return f * (o - l) + la; if (fn == 9) return l - f * l;\n"
"  if (fn == 16) return la - f * l; return l; }\n"
"float fog_w(float w) {\n"
"  if (w <= 1.0) return fogtab(0);\n"
"  float q = floor(log2(w)); float m = w / exp2(q);\n"
"  int r = m < 1.142857 ? 0 : m < 1.333333 ? 1 : m < 1.6 ? 2 : 3;\n"
"  int i = (int)q * 4 + r; if (i >= 63) return fogtab(63);\n"
"  int j = i + 1;\n"
"  float wi = exp2(3.0 + (float)(i >> 2)) / (float)(8 - (i & 3));\n"
"  float wj = exp2(3.0 + (float)(j >> 2)) / (float)(8 - (j & 3));\n"
"  return lerp(fogtab(i), fogtab(j), saturate((w - wi) / (wj - wi))); }\n"
"float4 ps_main(VOut i) : SV_Target {\n"
"  float4 tx = float4(1, 1, 1, 1);\n"
"  if (mode.x != 0) {\n"
"    float4 t = tex0.Sample(smp0, i.st);\n"
"    if (mode.z != 0 && all(abs(t.rgb - chroma.rgb) < 0.5 / 255.0)) discard;\n"
"    tx.r = comb(tcm.x, fv(tcm.y, t.r, t.a, 0, t.a), t.r, t.a, 0);\n"
"    tx.g = comb(tcm.x, fv(tcm.y, t.g, t.a, 0, t.a), t.g, t.a, 0);\n"
"    tx.b = comb(tcm.x, fv(tcm.y, t.b, t.a, 0, t.a), t.b, t.a, 0);\n"
"    tx.a = comb(tcm.z, fv(tcm.w, t.a, t.a, 0, t.a), t.a, t.a, 0);\n"
"    if (flags.z != 0) tx.rgb = 1.0 - tx.rgb; if (flags.w != 0) tx.a = 1.0 - tx.a;\n"
"  }\n"
"  float4 it = i.col;\n"
"  float la = ac.z == 1 ? constc.a : it.a;\n"
"  float oa = ac.w == 1 ? tx.a : ac.w == 2 ? constc.a : it.a;\n"
"  float outa = comb(ac.x, fv(ac.y, la, la, oa, tx.a), la, la, oa);\n"
"  if (flags.y != 0) outa = 1.0 - outa; outa = saturate(outa);\n"
"  float4 lc = cc.z == 1 ? constc : it;\n"
"  float4 oc = cc.w == 1 ? tx : cc.w == 2 ? constc : it;\n"
"  float3 o;\n"
"  o.r = comb(cc.x, fv(cc.y, lc.r, la, oa, tx.a), lc.r, la, oc.r);\n"
"  o.g = comb(cc.x, fv(cc.y, lc.g, la, oa, tx.a), lc.g, la, oc.g);\n"
"  o.b = comb(cc.x, fv(cc.y, lc.b, la, oa, tx.a), lc.b, la, oc.b);\n"
"  if (flags.x != 0) o = 1.0 - o;\n"
"  o = saturate(o);\n"
"  if (mode.z != 0 && mode.x == 0 && all(abs(o - chroma.rgb) < 0.5 / 255.0)) discard;\n"
"  float av = floor(outa * 255.0 + 0.001), rv = floor(aref.x * 255.0 + 0.5); bool ok = true;\n"
"  int at = mode.y;\n"
"  if (at == 0) ok = false; else if (at == 1) ok = av < rv; else if (at == 2) ok = av == rv;\n"
"  else if (at == 3) ok = av <= rv; else if (at == 4) ok = av > rv; else if (at == 5) ok = av != rv;\n"
"  else if (at == 6) ok = av >= rv;\n"
"  if (!ok) discard;\n"
"  if (mode.w != 0) {\n"
"    float f = mode.w == 1 ? i.fog : mode.w == 4 ? it.a : mode.w == 3 ? 0.0 : fog_w(i.oow > 1e-7 ? 1.0 / i.oow : 65535.0);\n"
"    o = lerp(o, fogc.rgb, saturate(f));\n"
"  }\n"
"  return float4(o, outa); }\n";

static const char GPU_MSL[] =
"#include <metal_stdlib>\nusing namespace metal;\n"
"struct VSU { float4 vsize; };\n"
"struct PSU { int4 cc; int4 ac; int4 tcm; int4 flags; int4 mode;\n"
"  float4 aref; float4 chroma; float4 fogc; float4 constc; float fogtab[64]; };\n"
"struct VIn { float4 p [[attribute(0)]]; float2 st [[attribute(1)]]; float fog [[attribute(2)]]; float4 col [[attribute(3)]]; };\n"
"struct VOut { float4 pos [[position]]; float2 st;\n"
"  float4 col [[center_no_perspective]]; float oow [[center_no_perspective]]; float fog [[center_no_perspective]]; };\n"
"vertex VOut vs_main(VIn i [[stage_in]], constant VSU &u [[buffer(1)]]) {\n"
"  VOut o; float w = i.p.w > 1e-7 ? 1.0 / i.p.w : 1.0;\n"
"  float2 ndc = float2(i.p.x / u.vsize.x * 2.0 - 1.0, 1.0 - i.p.y / u.vsize.y * 2.0);\n"
"  o.pos = float4(ndc * w, i.p.z * w, w); o.st = i.st; o.col = i.col; o.oow = i.p.w; o.fog = i.fog; return o; }\n"
"static float fv(int f, float l, float la, float oa, float ta) {\n"
"  int k = f & 7; float v = k == 0 ? 0.0 : k == 1 ? l : k == 2 ? oa : k == 3 ? la : k == 4 ? ta : 1.0;\n"
"  return (f & 8) ? 1.0 - v : v; }\n"
"static float comb(int fn, float f, float l, float la, float o) {\n"
"  if (fn == 0) return 0.0; if (fn == 1) return l; if (fn == 2) return la; if (fn == 3) return f * o;\n"
"  if (fn == 4) return f * o + l; if (fn == 5) return f * o + la; if (fn == 6) return f * (o - l);\n"
"  if (fn == 7) return f * (o - l) + l; if (fn == 8) return f * (o - l) + la; if (fn == 9) return l - f * l;\n"
"  if (fn == 16) return la - f * l; return l; }\n"
"static float fog_w(constant PSU &u, float w) {\n"
"  if (w <= 1.0) return u.fogtab[0];\n"
"  float q = floor(log2(w)); float m = w / exp2(q);\n"
"  int r = m < 1.142857 ? 0 : m < 1.333333 ? 1 : m < 1.6 ? 2 : 3;\n"
"  int i = int(q) * 4 + r; if (i >= 63) return u.fogtab[63];\n"
"  int j = i + 1;\n"
"  float wi = exp2(3.0 + float(i >> 2)) / float(8 - (i & 3));\n"
"  float wj = exp2(3.0 + float(j >> 2)) / float(8 - (j & 3));\n"
"  return mix(u.fogtab[i], u.fogtab[j], saturate((w - wi) / (wj - wi))); }\n"
"fragment float4 ps_main(VOut i [[stage_in]], constant PSU &u [[buffer(0)]],\n"
"                        texture2d<float> tex0 [[texture(0)]], sampler smp0 [[sampler(0)]]) {\n"
"  float4 tx = float4(1);\n"
"  if (u.mode.x != 0) {\n"
"    float4 t = tex0.sample(smp0, i.st);\n"
"    if (u.mode.z != 0 && all(abs(t.rgb - u.chroma.rgb) < 0.5 / 255.0)) discard_fragment();\n"
"    tx.r = comb(u.tcm.x, fv(u.tcm.y, t.r, t.a, 0, t.a), t.r, t.a, 0);\n"
"    tx.g = comb(u.tcm.x, fv(u.tcm.y, t.g, t.a, 0, t.a), t.g, t.a, 0);\n"
"    tx.b = comb(u.tcm.x, fv(u.tcm.y, t.b, t.a, 0, t.a), t.b, t.a, 0);\n"
"    tx.a = comb(u.tcm.z, fv(u.tcm.w, t.a, t.a, 0, t.a), t.a, t.a, 0);\n"
"    if (u.flags.z != 0) tx.rgb = 1.0 - tx.rgb; if (u.flags.w != 0) tx.a = 1.0 - tx.a;\n"
"  }\n"
"  float4 it = i.col;\n"
"  float la = u.ac.z == 1 ? u.constc.a : it.a;\n"
"  float oa = u.ac.w == 1 ? tx.a : u.ac.w == 2 ? u.constc.a : it.a;\n"
"  float outa = comb(u.ac.x, fv(u.ac.y, la, la, oa, tx.a), la, la, oa);\n"
"  if (u.flags.y != 0) outa = 1.0 - outa; outa = saturate(outa);\n"
"  float4 lc = u.cc.z == 1 ? u.constc : it;\n"
"  float4 oc = u.cc.w == 1 ? tx : u.cc.w == 2 ? u.constc : it;\n"
"  float3 o;\n"
"  o.r = comb(u.cc.x, fv(u.cc.y, lc.r, la, oa, tx.a), lc.r, la, oc.r);\n"
"  o.g = comb(u.cc.x, fv(u.cc.y, lc.g, la, oa, tx.a), lc.g, la, oc.g);\n"
"  o.b = comb(u.cc.x, fv(u.cc.y, lc.b, la, oa, tx.a), lc.b, la, oc.b);\n"
"  if (u.flags.x != 0) o = 1.0 - o;\n"
"  o = saturate(o);\n"
"  if (u.mode.z != 0 && u.mode.x == 0 && all(abs(o - u.chroma.rgb) < 0.5 / 255.0)) discard_fragment();\n"
"  float av = floor(outa * 255.0 + 0.001), rv = floor(u.aref.x * 255.0 + 0.5); bool ok = true;\n"
"  int at = u.mode.y;\n"
"  if (at == 0) ok = false; else if (at == 1) ok = av < rv; else if (at == 2) ok = av == rv;\n"
"  else if (at == 3) ok = av <= rv; else if (at == 4) ok = av > rv; else if (at == 5) ok = av != rv;\n"
"  else if (at == 6) ok = av >= rv;\n"
"  if (!ok) discard_fragment();\n"
"  if (u.mode.w != 0) {\n"
"    float f = u.mode.w == 1 ? i.fog : u.mode.w == 4 ? it.a : u.mode.w == 3 ? 0.0 : fog_w(u, i.oow > 1e-7 ? 1.0 / i.oow : 65535.0);\n"
"    o = mix(o, u.fogc.rgb, saturate(f));\n"
"  }\n"
"  return float4(o, outa); }\n";
